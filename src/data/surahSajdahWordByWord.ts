function normalizeArabicToken(text: string): string {
  return text
    .replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .trim();
}

function findMatchingRoot(word: string, roots: RootWord[]): RootWord | undefined {
  const normWord = normalizeArabicToken(word);
  if (!normWord) return undefined;

  return roots.find((rootEntry) => {
    const normRootArabic = normalizeArabicToken(rootEntry.arabic);
    if (!normRootArabic) return false;
    if (normWord === normRootArabic) return true;
    // Handle attached single-letter conjunction/preposition prefixes (و، ف، ب، ل، ك)
    const strippedPrefix = normWord.replace(/^[وفبلك]/, '');
    return strippedPrefix === normRootArabic || normWord.endsWith(normRootArabic);
  });
}

const STOP_MARK_REGEX = /^[\u06D6-\u06ED\u06E9]+$/;

export function getWordByWordTokens(ayah: AyahTafsir): WordByWordToken[] {
  const rawTokens = ayah.arabic
    .split(/\s+/)
    .filter((token) => token.length > 0 && !STOP_MARK_REGEX.test(token));

  const glosses = WORD_GLOSSES[ayah.number] ?? [];

  return rawTokens.map((arabicToken, idx) => {
    const rootInfo = findMatchingRoot(arabicToken, ayah.roots);
    const literal = glosses[idx] ?? {
      en: rootInfo?.meaningEn ?? '—',
      id: rootInfo?.meaningId ?? '—',
      ms: rootInfo?.meaningMs ?? '—',
    };

    return {
      arabic: arabicToken,
      literal,
      rootInfo,
    };
  });
}
